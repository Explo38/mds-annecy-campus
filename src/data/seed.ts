/**
 * Horodatage d'un enregistrement créé pendant la session : on avance depuis
 * DEMO_NOW du temps réellement écoulé, pour rester dans la chronologie de la
 * démonstration tout en gardant les créations dans l'ordre.
 */
export function demoNowIso(): string {
  return toIso(new Date(DEMO_NOW.getTime() + (Date.now() - BOOT)));
}

